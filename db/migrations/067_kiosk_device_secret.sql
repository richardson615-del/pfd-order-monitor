-- 067: a tablet has to prove it is the tablet, not just know its serial
-- (SH1 / Z-02, CRM QUEUE row 293).
--
-- POST /api/kiosk/bootstrap is unauthenticated: a tablet with no session is
-- the caller. Until now the device reference alone (the Hexnode serial, or
-- aid:<ANDROID_ID>) was enough to be handed a session for the restaurant it
-- is bound to - and the serial is printed on the device and shown in the CRM.
--
-- secret_hash is the sha256 (lowercase hex) of a 32-byte secret that only the
-- tablet holds. The secret itself is never stored here. Two sources:
--   aid: references   issued when the tablet collects a link code
--                     (/api/kiosk/link-status) and kept in its localStorage
--   Hexnode serials   generated by the CRM, which stores only the hash here
--                     (/api/crm/devices/:ref/secret); the secret reaches the
--                     tablet through Hexnode managed app configuration
--
-- null = no secret yet. Such a row bootstraps exactly as before until
-- KIOSK_REQUIRE_SECRET is switched on, so this migration changes nothing for
-- a tablet on a wall today. Service role only, like the rest of the table.
-- Safe to run twice.

alter table kiosk_devices
  add column if not exists secret_hash text;

do $$
begin
  if not exists (select 1 from pg_constraint where conname = 'kiosk_devices_secret_hash_shape') then
    alter table kiosk_devices
      add constraint kiosk_devices_secret_hash_shape
      check (secret_hash is null or secret_hash ~ '^[0-9a-f]{64}$');
  end if;
end $$;

comment on column kiosk_devices.secret_hash is
  'sha256 hex of the device secret a tablet must present to bootstrap (SH1). Never the secret. null = none set: bootstraps by reference alone unless KIOSK_REQUIRE_SECRET is on.';
