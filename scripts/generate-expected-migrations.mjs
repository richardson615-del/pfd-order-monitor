#!/usr/bin/env node
/**
 * Writes lib/expected-migrations.ts from whatever is in db/migrations/.
 *
 * Generated rather than hand-listed so the list cannot fall behind the
 * folder. A migration added without being listed would deploy and report
 * nothing missing - a health check that says "up to date" about a database
 * that is not is worse than having no check.
 *
 * Runs as part of build, same as prs-crm does it.
 */
import { readdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const MIGRATIONS_DIR = fileURLToPath(new URL("../db/migrations/", import.meta.url));
const OUT = fileURLToPath(new URL("../lib/expected-migrations.ts", import.meta.url));

const files = (await readdir(MIGRATIONS_DIR)).filter((f) => f.endsWith(".sql")).sort();

const body = `// GENERATED by scripts/generate-expected-migrations.mjs - do not edit.
// Every migration this build expects the database to have. Compared against
// schema_migrations by lib/schema-check.ts and reported at /api/health.
export const EXPECTED_MIGRATIONS: readonly string[] = [
${files.map((f) => `  ${JSON.stringify(f)},`).join("\n")}
];
`;

await writeFile(OUT, body);
console.log(`Wrote ${files.length} expected migration(s) to lib/expected-migrations.ts`);
